"""Shared, dependency-free builders for the test suite.

Nothing here touches the network or the repository working tree.  Everything
is a deterministic function of its arguments so that any golden value recorded
in a test can be regenerated by calling the same helper with the same numbers.
"""

from __future__ import annotations

import dataclasses

import numpy as np

from vqcdepth import config
from vqcdepth.splits import Split, split_hashes

PI = config.FEATURE_RANGE[1]


# ----------------------------------------------------------------------
# Synthetic raw dataset (stands in for data.load_dataset)
# ----------------------------------------------------------------------
def synthetic_raw(
    n: int = 120,
    seed: int = 0,
    n_nan: int = 0,
    pos_frac: float = 0.45,
) -> tuple[np.ndarray, np.ndarray, list[str]]:
    """A (n, 4) float64 / (n,) int64 dataset shaped exactly like the real ones.

    Two loosely separated class means so that F1 is not degenerate, feature
    scales deliberately different per column (1, 10, 100, 0.01) so that a
    scaler fitted on the wrong partition is easy to spot.  ``n_nan`` missing
    values are punched into columns 0 and 2 only, never making a row fully NaN
    (``data._validate`` forbids that, and the median imputation could not
    recover it).
    """
    rng = np.random.default_rng(9_000 + seed)
    y = (rng.random(n) < pos_frac).astype(np.int64)
    # guarantee both classes are present and large enough to stratify 70/15/15
    y[:4] = np.array([0, 1, 0, 1], dtype=np.int64)
    base = np.where(y[:, None] == 1, 0.8, -0.4)
    X = base + 0.5 * rng.standard_normal((n, config.N_QUBITS))
    X *= np.array([1.0, 10.0, 100.0, 0.01])
    X = np.ascontiguousarray(X, dtype=np.float64)
    if n_nan:
        rows = rng.choice(n, size=n_nan, replace=False)
        cols = rng.integers(0, 2, size=n_nan) * 2      # column 0 or column 2
        X[rows, cols] = np.nan
    names = ["f0", "f1", "f2", "f3"]
    return X, y, names


# ----------------------------------------------------------------------
# Synthetic Split (stands in for splits.make_split)
# ----------------------------------------------------------------------
def synthetic_split(
    dataset: str = "banknote",
    seed: int = 0,
    n_train: int = 96,
    n_val: int = 48,
    n_test: int = 48,
) -> Split:
    """A ready-to-train Split with features already inside [0, pi].

    Used by every training test so that they depend on neither the network nor
    ``data/cache``.  Deterministic function of the arguments only.
    """
    rng = np.random.default_rng(1_000 + seed)
    total = n_train + n_val + n_test
    y = (rng.random(total) < 0.5).astype(np.int64)
    y[:4] = np.array([0, 1, 0, 1], dtype=np.int64)
    mu = np.where(y[:, None] == 1, 1.9, 1.2)
    X = np.clip(mu + 0.35 * rng.standard_normal((total, config.N_QUBITS)), 0.0, PI)
    X = np.ascontiguousarray(X, dtype=np.float64)

    idx = np.arange(total, dtype=np.int64)
    sl_tr, sl_va, sl_te = slice(0, n_train), slice(n_train, n_train + n_val), slice(
        n_train + n_val, total)
    return Split(
        dataset=dataset,
        seed=int(seed),
        idx_train=idx[sl_tr], idx_val=idx[sl_va], idx_test=idx[sl_te],
        X_train=X[sl_tr], y_train=y[sl_tr],
        X_val=X[sl_va], y_val=y[sl_va],
        X_test=X[sl_te], y_test=y[sl_te],
        feature_names=[f"f{i}" for i in range(config.N_QUBITS)],
        hashes=split_hashes(idx[sl_tr], idx[sl_va], idx[sl_te]),
        n_imputed={"train": 0, "val": 0, "test": 0, "total": 0},
    )


def poison_test_partition(split: Split, seed: int = 1234) -> Split:
    """Same Split with X_test / y_test replaced by pure noise.

    If anything in the training path reads the test partition, results computed
    from this Split will differ from results computed from the original.
    """
    rng = np.random.default_rng(seed)
    n, d = split.X_test.shape
    return dataclasses.replace(
        split,
        X_test=np.ascontiguousarray(rng.uniform(-50.0, 50.0, (n, d)), dtype=np.float64),
        y_test=np.ascontiguousarray(1 - split.y_test, dtype=np.int64),
    )


# ----------------------------------------------------------------------
# Reference (golden) pre-processing model -- deliberately naive
# ----------------------------------------------------------------------
def reference_preprocess(
    X_raw_train: np.ndarray, X_raw_other: list[np.ndarray]
) -> tuple[np.ndarray, list[np.ndarray], np.ndarray]:
    """Impute with the TRAIN median, then min-max to [0, pi] with TRAIN bounds.

    Independent, obviously-correct re-implementation of what
    ``splits.make_split`` must do -- written without sklearn so a change of
    sklearn version cannot make both sides wrong in the same way.
    """
    med = np.nanmedian(X_raw_train, axis=0)
    tr = np.where(np.isnan(X_raw_train), med, X_raw_train)
    others = [np.where(np.isnan(a), med, a) for a in X_raw_other]

    lo, hi = tr.min(axis=0), tr.max(axis=0)
    span = np.where(hi - lo == 0.0, 1.0, hi - lo)   # sklearn's degenerate-column rule

    def scale(a):
        return (a - lo) / span * PI

    return scale(tr), [scale(a) for a in others], med
